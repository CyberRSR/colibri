"""KV prefix reuse and Brio photos on MiMo-V2.6, against the tiny fixture.

MiMo is the engine where a photo is more than token ids. Most of its layers
attend a sliding window, and a windowed layer keeps its keys in a RING: position
p in slot p % window. The photo of a prompt of P tokens holds the ring as it was
at P; the first option then writes its own positions into the slots of P - window
and onwards, so after one option the ring no longer describes the photo. A photo
that kept only the ids -- enough for the full-attention layers, whose rows below
P nobody touches -- would hand the second option a ring from the first. The
fixture's window is 8 tokens, and every prompt below outgrows it.

What is checked, all against a cold engine and to the last printed digit of
every ECHO frame (the log-probability of the token and the whole top-k):

  - the shared prefix-reuse contract (tests/prefix_serve_harness.py);
  - options that cross the window resume from the photo exactly, one after the
    other, with an ordinary chat turn in between that must not take the photo
    away, and each one PROCESSES ONLY ITS OWN TOKENS: its read-out starts at the
    photo's end and the engine says it prefilled the option and nothing more.
    The numbers alone would not show a photo that silently fell back to a full
    recompute; the positions and the count do;
  - nested photos (a state, then a question) and a sibling question that
    overwrites the deeper one's rows: the engine falls back to the shallower;
  - a photo whose rows an unrelated prompt overwrote is released, not restored;
  - pictures: a prompt with an image never resumes from a photo, and a prompt
    with an image takes none, because token ids do not describe the picture;
  - the read-out covers every position from 0 unless a photo covers the prefix,
    which is what the gateway's `echo` needs, and never resumes from a live
    prefix;
  - asking for logprobs changes no generated byte;
  - a read-only request may fill the context, a generating one may not;
  - turn photos: an agent loop whose client sends each reply back without its
    reasoning -- so no turn is a prefix of the live state -- resumes every turn
    from the photo of the turn before and prefills only what follows it, with
    the prompt's logits, the reply and the MTP drafts the bytes of the same
    prompt computed cold; System One keeps its own photos, a read-out never
    resumes from a turn photo, and the switches turn them off. With
    MIMO_CUDA_TEST=1, the same on the GPU, where a short tail takes the kernels
    of the whole prompt (MIMO_PROMPT_KERNELS) and without them is not the cold
    prompt's bytes.

Needs the built engine and the fixture: `make mimo mimo-tiny-generate`.
"""
