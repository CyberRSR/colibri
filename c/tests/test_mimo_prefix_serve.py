def window():
    config = json.loads((fixture.FIXTURE / "config.json").read_text())
    return int(config["sliding_window"])


class Client(ServeEngine):
    """A serve engine read frame by frame: the ECHO frames are what is compared."""

    def __init__(self, log_prefix=True, **env):
        super().__init__(fixture.ENGINE, ["8"], fixture.engine_env(**env),
                         log_prefix=log_prefix)

    def image(self, rid):
        payload, grid_h, grid_w, _pads = fixture.image_payload()
        self.p.stdin.write(f"IMAGE {rid} {len(payload)} {grid_h} {grid_w}\n".encode()
                           + payload + b"\n")
        self.p.stdin.flush()

    def submit(self, rid, prompt, max_tokens=0, ext=" logprobs=3"):
        """Returns {kind: ..., "echo": {pos: tail}, "data": [(bytes, tail)], "end": line}.

        A tail is the frame's numeric part after the position, compared as text:
        the log-probability and every top-k candidate, as the engine printed them."""
        data = prompt.encode()
        self.p.stdin.write(f"SUBMIT {rid} 0 {len(data)} {max_tokens} 0 1{ext}\n".encode()
                           + data + b"\n")
        self.p.stdin.flush()
        out = {"echo": {}, "data": [], "accept": None, "end": None}
        while True:
            line = self.p.stdout.readline()
            if not line:
                raise RuntimeError("engine closed mid-request:\n" + "".join(self._err)[-2000:])
            fields = line.decode("latin-1").split()
            if not fields:
                continue
            if fields[0] in ("ECHO", "DATA"):
                payload = self.p.stdout.read(int(fields[2]))
                self.p.stdout.read(1)
                if fields[0] == "ECHO":
                    pos = int(fields[3])
                    if pos in out["echo"]:
                        raise AssertionError(f"position {pos} read out twice")
                    out["echo"][pos] = " ".join(fields[4:])
                else:
                    out["data"].append((payload, " ".join(fields[3:])))
            elif fields[0] == "ACCEPT":
                out["accept"] = int(fields[2])
            elif fields[0] in ("DONE", "ERROR"):
                out["end"] = fields
                return out


def resumed(log):
    """[(photo length, tokens prefilled)] in order, from the engine's own account."""
    return [(int(a), int(b)) for a, b in
            re.findall(r"\[PIN\] resumed from the photo of (\d+) tokens, (\d+) to prefill", log)]


