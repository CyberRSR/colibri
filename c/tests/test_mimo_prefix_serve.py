@unittest.skipUnless(fixture.available() and os.environ.get("MIMO_CUDA_TEST") == "1",
                     "explicit CUDA hardware test (MIMO_CUDA_TEST=1) with the built engine and fixture")
class MimoTurnPhotoCudaTest(TurnRuns, unittest.TestCase):
    """On the GPU a step's kernels depend on its rows: 64 or more take the prompt
    kernels, fewer the decode path. Each turn here adds about 40 tokens, so a tail
    resumed from a photo would run on the decode path where the same prompt cold
    runs on the GPU -- unless a prompt's rows take the kernels of its length."""
    ENV = {"MIMO_CUDA": "1", "MIMO_CUDA_DENSE_GB": "20", "COLI_VULKAN": "0", "COLI_GPU": "0"}

    def test_a_short_tail_is_the_cold_prompt_to_the_bit(self):
        prompts = turn_prompts(4)
        n = [len(p.encode()) for p in prompts]
        self.assertGreaterEqual(n[0], 64, "the first turn must take the GPU's prompt kernels")
        self.assertTrue(all(b - a < 64 for a, b in zip(n, n[1:])), "a tail must be short of them")
        for attn_rows in ("1024", "64"):   # 64: a block's last attention piece of a few rows
            with self.subTest(MIMO_ATTN_ROWS=attn_rows):
                outs, log, logits, steps = self.run_turns(prompts, MIMO_ATTN_ROWS=attn_rows)
                self.assertIn("experts on the GPU", log)
                self.assertEqual(resumed(log), [(n[i], n[i + 1] - n[i]) for i in range(3)], log)
                for i in range(1, 4):
                    self.assertTurnIsCold(prompts[i], outs[i], logits[i], steps[i], MIMO_ATTN_ROWS=attn_rows)

    def test_without_the_prompts_kernels_a_tail_is_not_the_cold_prompt(self):
        """MIMO_PROMPT_KERNELS=0, the step-by-step choice: the tail on the decode
        path gives other bytes than the prompt cold -- what makes the test above
        bite. That mode gave up those bytes for a short tail's speed, so it takes
        every turn's photo."""
        prompts = turn_prompts(3)
        n = [len(p.encode()) for p in prompts]
        outs, log, logits, _steps = self.run_turns(prompts, MIMO_PROMPT_KERNELS="0")
        self.assertEqual(resumed(log), [(n[0], n[1] - n[0]), (n[1], n[2] - n[1])], log)
        self.assertEqual(log.count("[PIN] turn photo of"), 3, log)
        _cold, _log, cold_logits, _ = self.run_turns(prompts[1:2], MIMO_PROMPT_KERNELS="0")
        self.assertNotEqual(logits[1], cold_logits[0])

    def test_a_live_prefix_keeps_its_own_kernels_and_takes_no_photo(self):
        """A client that sends the reply back as the model wrote it resumes from the
        live state, whose reply decode steps computed: no kernel choice makes that
        the cold prompt, so its tail keeps its steps' kernels (the decode path, the
        faster for a few rows), as before, and no photo stands for it. Here the first
        turn emits one token, which is never fed: the live state is the prompt cold,
        so the tail's own kernels are what makes the second turn differ from it."""
        prompts = [TURN_OPENING, TURN_OPENING + TURN_ASKS[0]]
        outs, log, logits, _steps = self.run_turns(prompts, max_tokens=1)
        self.assertEqual(resumed(log), [], log)
        self.assertRegex(log, r"\[PREFIX\] reusing %d of %d prompt tokens\r?\n" % tuple(len(p.encode()) for p in prompts))
        self.assertEqual(log.count("[PIN] turn photo of"), 1, log)
        self.assertIn("[PIN] no turn photo", log)
        _cold, _log, cold_logits, _ = self.run_turns(prompts[1:], max_tokens=1)
        self.assertNotEqual(logits[1], cold_logits[0])


